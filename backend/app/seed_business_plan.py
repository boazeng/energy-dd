def seed_business_plan(db: Session) -> None:
    """זורע פרקים חסרים בלבד. עריכות קיימות אינן נדרסות."""
    if db.get(BusinessPlanSetting, 1) is None:
        db.add(BusinessPlanSetting(id=1))

    existing = set(db.scalars(select(BusinessPlanSection.key)))
    added = 0
    for key, order, level, title, data_block, body in SECTIONS:
        if key in existing:
            continue
        db.add(BusinessPlanSection(
            key=key, order=order, level=level, title=title,
            data_block=data_block, body=body.strip(),
        ))
        added += 1

    if added or db.new:
        db.commit()
